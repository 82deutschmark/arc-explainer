def _ground(h, lower):
    px = [[TERRAIN[h]] * CELL for _ in range(CELL)]
    up, right, down, left = lower
    for i in range(CELL):
        if up:
            px[0][i] = BLACK
        if down:
            px[CELL - 1][i] = BLACK
        if left:
            px[i][0] = BLACK
        if right:
            px[i][CELL - 1] = BLACK
    return px


def _rock():
    return _px(ROCK, {"k": BLACK, "p": PURPLE})


def _pad(need, lit):
    px = _px(PAD, {"k": BLACK, "f": WHITE if lit else LBLUE})
    for x, y in LATTICE[min(need, 6)]:
        px[y][x] = ORANGE if lit else BLACK
    return px


def _bellpad(active, lit):
    if active:
        return _px(BELLPAD_ON, {"k": BLACK, "f": WHITE if lit else LBLUE, "W": WHITE})
    return _px(BELLPAD, {"k": BLACK, "f": WHITE if lit else LBLUE, "O": ORANGE})


def _bell(active):
    if active:
        return _px(BELL_ON, {"k": BLACK, "w": WHITE, "o": ORANGE})
    return _px(BELL, {"k": BLACK, "o": ORANGE, "w": WHITE})


def _door(live):
    if live:
        return _px(DOOR_LIVE, {"w": WHITE, "y": YELLOW})
    return _px(DOOR_SHUT, {"k": BLACK, "m": MAROON, "y": YELLOW})


def _guard(load, face):
    px = _px(GUARD, {"r": RED})
    for x, y in BELLY[min(load, 6)]:
        px[y][x] = WHITE
    if face == 1:  # up: the back of the head
        px[1][3] = MAROON
    elif face == 2:
        px[2][3] = px[2][5] = BLACK
    elif face == 4:
        px[2][1] = px[2][3] = BLACK
    else:
        px[2][2] = px[2][4] = BLACK
    return px


def _player(pose):
    if pose == "hit":
        return _px(PLAYER, {"k": PINK, "w": WHITE})
    if pose == "fall":
        return _px(HEAP, {"p": PINK})
    if pose == "puff":
        return _px(PUFF, {"p": PINK})
    if pose == "half":
        rows = PLAYER[:4] + (".......",) * 3
        return _px(rows, {"k": BLACK, "w": WHITE})
    if pose == "gone":
        return [[-1] * CELL for _ in range(CELL)]
    return _px(PLAYER, {"k": BLACK, "w": WHITE})


_BUILD = {"ground": _ground, "rock": _rock, "pad": _pad, "bellpad": _bellpad, "bell": _bell,
          "door": _door, "guard": _guard, "player": _player}
_TILES: dict = {}


def tile(kind: str, *args) -> np.ndarray:
    key = (kind,) + args
    if key not in _TILES:
        _TILES[key] = np.array(_BUILD[kind](*args), dtype=np.int8)
    return _TILES[key]


def _ring_masks():
    n = 64
    band = np.zeros((n, n), dtype=bool)
    black = np.zeros((n, n), dtype=bool)
    for y in range(n):
        for x in range(n):
            d = min(x, y, n - 1 - x, n - 1 - y)
            if d >= MARGIN:
                continue
            if d in (0, MARGIN - 1):
                black[y, x] = True
                continue
            along = y if min(x, n - 1 - x) < min(y, n - 1 - y) else x
            if (along + 2 * (d - 1)) % 4 == 0:
                black[y, x] = True
            else:
                band[y, x] = True
    return band, black


_BAND, _BLACKS = _ring_masks()


# ---------------------------------------------------------------------------------------------
# Engine glue: sprites, the overlay, and the turn. The rules above decide the whole outcome of
# an action once; the frames below only show it.
# ---------------------------------------------------------------------------------------------
def _pixel(cell):
    return MARGIN + cell[0] * CELL, MARGIN + cell[1] * CELL


def _lower_sides(m, cell):
    h = m["height"][cell]
    return tuple((cell[0] + dx, cell[1] + dy) in m["floor"] and m["height"][(cell[0] + dx, cell[1] + dy)] < h
                 for dx, dy in NEIGHBOURS)


def _things(m):
    kinds = {b: "bell" for b in m["bells"]}
    for cell, _ in m["plates"]:
        kinds[cell] = "bellpad" if cell in kinds else "pad"
    return kinds


def _thing_tile(m, cell, kind, held_now, active):
    if kind == "bell":
        return tile("bell", active)
    need = dict(m["plates"])[cell]
    if kind == "pad":
        return tile("pad", need, held_now)
    return tile("bellpad", active, held_now)


def _sprite(px, name, x, y, layer, tags=()):
    return Sprite(pixels=px, name=name, blocking=BlockingMode.NOT_BLOCKED,
                  interaction=InteractionMode.INTANGIBLE, layer=layer,
                  tags=list(tags)).set_position(x, y)


def build_levels() -> list:
    levels = []
    for index in range(len(LEVELS)):
        m = model(index)
        sprites = []
        for y in range(ROWS):
            for x in range(COLS):
                cell = (x, y)
                px, py = _pixel(cell)
                if cell in m["floor"]:
                    sprites.append(_sprite(tile("ground", m["height"][cell], _lower_sides(m, cell)),
                                           f"ground_{x}_{y}", px, py, -3, ("ground",)))
                else:
                    sprites.append(_sprite(tile("rock"), f"rock_{x}_{y}", px, py, -3, ("rock",)))
        for cell, kind in _things(m).items():
            px, py = _pixel(cell)
            sprites.append(_sprite(_thing_tile(m, cell, kind, False, False), f"thing_{cell[0]}_{cell[1]}",
                                   px, py, -1, (kind,)))
        px, py = _pixel(m["exit"])
        sprites.append(_sprite(tile("door", False), "exit", px, py, 0, ("exit",)))
        for i, cell in enumerate(m["posts"]):
            px, py = _pixel(cell)
            sprites.append(_sprite(tile("guard", m["loads"][i], 0), f"guard_{i}", px, py, 2, ("guard",)))
        px, py = _pixel(m["start"])
        sprites.append(_sprite(tile("player", "idle"), "player", px, py, 3, ("player",)))
        levels.append(Level(sprites=sprites, grid_size=(64, 64)))
    return levels


def _faces(m, guards, target):
    out = []
    for g in guards:
        face = 0
        if target is not None:
            nxt = guard_step(m, g, target)
            if nxt != g:
                face = {(0, -1): 1, (1, 0): 2, (0, 1): 3, (-1, 0): 4}[(nxt[0] - g[0], nxt[1] - g[1])]
        out.append(face)
    return out


def _danger(m, guards, target):
    """Squares where a move would be caught: where the guards will stand after their next step and the
    four beside each, plus any bell that would send them to a place that catches you on that bell."""
    ahead = advance(m, guards, target) if target is not None else guards
    cells = set(ahead)
    for g in ahead:
        for dx, dy in NEIGHBOURS:
            c = (g[0] + dx, g[1] + dy)
            if c in m["floor"]:
                cells.add(c)
    for i, b in enumerate(m["bells"]):
        if any(grid_distance(g, b) <= 1 for g in advance(m, guards, i)):
            cells.add(b)
    return sorted(cells)


class Overlay(RenderableUserDisplay):
    """The brick border, the glow round a pad that is holding, and a load in flight."""

    def __init__(self, game: "G019") -> None:
        super().__init__()
        self._game = game

    def render_interface(self, frame: np.ndarray) -> np.ndarray:
        view = self._game.view
        if view is None:
            return frame
        frame[_BAND] = {"normal": PURPLE, "live": WHITE, "death": RED}[view["ring"]]
        frame[_BLACKS] = BLACK
        m = model(self._game.level_index)
        for lit, (cell, _) in zip(view["lit"], m["plates"]):
            if not lit:
                continue
            x0, y0 = _pixel(cell)
            for i in range(CELL):
                for x, y in ((x0 + i, y0), (x0 + i, y0 + CELL - 1), (x0, y0 + i), (x0 + CELL - 1, y0 + i)):
                    if int(frame[y, x]) not in (RED, MAROON):
                        frame[y, x] = WHITE
        for cell in view.get("zone", ()):
            x0, y0 = _pixel(cell)
            for yy in range(y0 + 1, y0 + CELL - 1):
                for xx in range(x0 + 1, x0 + CELL - 1):
                    if (xx + yy) % 2 == 0 and int(frame[yy, xx]) in (BLUE, GREEN, YELLOW, LBLUE):
                        frame[yy, xx] = PINK
        for fx, fy in view["flights"]:
            frame[fy - 1:fy + 3, fx - 1:fx + 3] = BLACK
            frame[fy:fy + 2, fx:fx + 2] = WHITE
        return frame


def _lerp(a, b, num, den):
    return (a[0] + round((b[0] - a[0]) * num / den), a[1] + round((b[1] - a[1]) * num / den))


class G019(ARCBaseGame):

    HIT_FRAMES = 5
    FALL_FRAMES = 4
    PUFF_FRAMES = 2

    def __init__(self) -> None:
        self.pos = (0, 0)
        self.guards = ()
        self.loads = ()
        self.target = None
        self.script = []
        self.view = None
        self._refs = {}
        camera = Camera(width=64, height=64, background=BLACK, letter_box=BLACK,
                        interfaces=[Overlay(self)])
        super().__init__(game_id="g019", levels=build_levels(), camera=camera,
                         available_actions=[1, 2, 3, 4])

    # -- the level ---------------------------------------------------------------------------
    def on_set_level(self, level: Level) -> None:
        m = model(self.level_index)
        analyse(self.level_index)
        self.pos, self.guards, self.loads, self.target = start_state(m)
        self.script = []
        self._refs = {s.name: s for s in level.get_sprites()
                      if s.name == "player" or s.name == "exit" or s.name.startswith(("guard_", "thing_"))}
        self._paint(self._settled())

    def _settled(self, state=None) -> dict:
        m = model(self.level_index)
        pos, guards, loads, target = state or (self.pos, self.guards, self.loads, self.target)
        flags = held(m, guards, loads)
        live = bool(flags) and all(flags)
        return {"p": _pixel(pos), "pose": "idle", "g": [_pixel(c) for c in guards], "loads": list(loads),
                "face": _faces(m, guards, target), "lit": list(flags), "live": live,
                "bell": target, "ring": "live" if live else "normal", "flights": [],
                "zone": _danger(m, guards, target)}

    def _paint(self, view: dict) -> None:
        self.view = view
        m = model(self.level_index)
        for i, (gx, gy) in enumerate(view["g"]):
            s = self._refs[f"guard_{i}"]
            s.pixels = tile("guard", min(view["loads"][i], 6), view["face"][i])
            s.set_position(gx, gy)
        s = self._refs["player"]
        s.pixels = tile("player", view["pose"])
        s.set_position(*view["p"])
        plate_at = {cell: i for i, (cell, _) in enumerate(m["plates"])}
        active = m["bells"][view["bell"]] if view["bell"] is not None else None
        for cell, kind in _things(m).items():
            held_now = view["lit"][plate_at[cell]] if cell in plate_at else False
            self._refs[f"thing_{cell[0]}_{cell[1]}"].pixels = _thing_tile(m, cell, kind, held_now, cell == active)
        self._refs["exit"].pixels = tile("door", view["live"])

    # -- one action --------------------------------------------------------------------------
    def step(self) -> None:
        if self.action.id == GameAction.RESET:
            self.complete_action()
            return
        if not self.script and not self._begin():
            self.complete_action()
            return
        view = self.script.pop(0)
        end = view.get("end")
        if end == "restart":
            taken = self._action_count
            self.level_reset()
            self._action_count = max(1, taken)
        elif end == "next":
            self.next_level()
        else:
            self._paint(view)
            if self.script:
                return
        self.complete_action()

    def _begin(self) -> bool:
        move = MOVES.get(self.action.id)
        if move is None:
            return False
        m = model(self.level_index)
        old = (self.pos, self.guards, self.loads, self.target)
        flows: list = []
        pos, guards, loads, target, caught, won = resolve(m, *old, move, flows)
        new = (pos, guards, loads, target)
        stuck = (not caught) and (not won) and new not in analyse(self.level_index)
        self.pos, self.guards, self.loads, self.target = new
        self.script = self._frames(m, old, new, move, flows, caught or stuck, won)
        return True

    def _frames(self, m, old, new, move, flows, dies, won) -> list:
        op, og, ol, ot = old
        np_, ng, nl, nt = new
        bumped = np_ == op
        moved = any(a != b for a, b in zip(og, ng))
        steps = 3 if (not bumped or moved) else 2
        before = self._settled(old)
        after = self._settled(new)
        frames = []
        for k in range(1, steps + 1):
            v = dict(before)
            v["p"] = _lerp(_pixel(op), _pixel(np_), k, steps)
            if bumped and k < steps:
                v["p"] = (v["p"][0] + move[0], v["p"][1] + move[1])
            v["g"] = [_lerp(_pixel(a), _pixel(b), k, steps) for a, b in zip(og, ng)]
            v["face"] = [self._heading(m, a, b, f) for a, b, f in zip(og, ng, before["face"])]
            v["flights"] = []
            frames.append(v)
        # a load in flight: the giver shows what it keeps, the taker what it had
        if flows and not dies:
            shown = [min(a, b) for a, b in zip(ol, nl)]
            for k in (1, 2, 3):
                v = dict(after)
                v["loads"] = shown
                v["lit"] = list(before["lit"])
                v["live"] = before["live"]
                v["ring"] = before["ring"]
                v["flights"] = [_lerp((_pixel(ng[i])[0] + 2, _pixel(ng[i])[1] + 3),
                                      (_pixel(ng[j])[0] + 2, _pixel(ng[j])[1] + 3), k, 4) for i, j in flows]
                frames.append(v)
            frames.append(dict(after))
        else:
            last = dict(after)
            frames[-1] = last
        if dies:
            for pose, count in (("hit", self.HIT_FRAMES), ("fall", self.FALL_FRAMES), ("puff", self.PUFF_FRAMES)):
                for _ in range(count):
                    v = dict(after)
                    v["pose"] = pose
                    v["ring"] = "death"
                    v["lit"] = [False] * len(after["lit"])
                    v["live"] = False
                    v["zone"] = []
                    frames.append(v)
            frames.append({"end": "restart"})
        elif won:
            for pose, count in (("idle", 2), ("half", 2), ("gone", 1)):
                for _ in range(count):
                    v = dict(after)
                    v["pose"] = pose
                    v["ring"] = "live"
                    v["live"] = True
                    v["zone"] = []
                    frames.append(v)
            frames.append({"end": "next"})
        return frames

    @staticmethod
    def _heading(m, a, b, face):
        if a == b:
            return face
        return {(0, -1): 1, (1, 0): 2, (0, 1): 3, (-1, 0): 4}[(b[0] - a[0], b[1] - a[1])]
