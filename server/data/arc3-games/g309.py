class World:

    def __init__(self, spec: dict) -> None:
        self.rows = spec["rows"]
        self.h = len(self.rows)
        self.w = len(self.rows[0])
        self.start = tuple(spec["start"])
        self.rw, self.rh = spec["rw"], spec["rh"]
        self.cols, self.regions_r = spec["cols"], spec["regions_r"]
        self.edge = spec["edge"]
        self.count_dark = spec["count_dark"]
        self.stations = [dict(pos=tuple(p), kind=LANTERN if k == "lantern" else BOOTS)
                         for p, k in spec["stations"]]
        self.props = [dict(pos=tuple(p), hue=PROP_HUE[i % len(PROP_HUE)])
                      for i, p in enumerate(spec["props"])]

        self.counts = set()
        for y, row in enumerate(self.rows):
            for x, ch in enumerate(row):
                if ch == PALE_CH or (ch == DARK_CH and self.count_dark):
                    self.counts.add((x, y))

        self.regions = self.cols * self.regions_r
        self.owed = [set() for _ in range(self.regions)]
        for cell in self.counts:
            self.owed[self.region_of(*cell)].add(cell)

    def region_of(self, x: int, y: int) -> int:
        c = min(self.cols - 1, max(0, (x - 1) // self.rw))
        r = min(self.regions_r - 1, max(0, (y - 1) // self.rh))
        return r * self.cols + c

    def at(self, x: int, y: int) -> str:
        if not (0 <= x < self.w and 0 <= y < self.h):
            return WALL_CH
        return self.rows[y][x]

    def walkable(self, x: int, y: int, booted: bool) -> bool:
        ch = self.at(x, y)
        if ch in (PALE_CH, DARK_CH):
            return True
        return ch == RUBBLE_CH and booted


WORLDS = [World(s) for s in LEVELS]


def build_levels() -> list[Level]:
    return [Level(sprites=[Sprite(pixels=[[DARKNESS] * CELL] * CELL, name="body",
                                  blocking=BlockingMode.NOT_BLOCKED,
                                  interaction=InteractionMode.INTANGIBLE, layer=1)
                           .set_position(wd.start[0] * CELL, wd.start[1] * CELL)])
            for wd in WORLDS]


class Window(RenderableUserDisplay):

    def __init__(self, game: "Cartographer") -> None:
        super().__init__()
        self._g = game

    def render_interface(self, frame: np.ndarray) -> np.ndarray:
        g = self._g
        wd = g.world
        frame[:] = DARKNESS
        for sy in range(VIEW):
            for sx in range(VIEW):
                wx, wy = sx + g.cam_x, sy + g.cam_y
                if (wx, wy) not in g.lit:
                    continue
                patch = frame[sy * CELL:(sy + 1) * CELL, sx * CELL:(sx + 1) * CELL]
                ch = wd.at(wx, wy)
                if ch == WALL_CH:
                    patch[:] = WALL
                    dec = _hash(wx, wy, g.level_index + 3)
                    if dec % 7 == 0:
                        patch[1:3, 1:3] = DARKNESS
                    continue
                if ch == RUBBLE_CH:
                    patch[:] = RUBBLE
                    patch[0, 0] = DARKNESS
                    patch[3, 3] = DARKNESS
                    continue
                patch[:] = PALE if ch == PALE_CH else DARK

        for i, q in enumerate(wd.props):
            sx, sy = q["pos"][0] - g.cam_x, q["pos"][1] - g.cam_y
            if q["pos"] in g.lit and 0 <= sx < VIEW and 0 <= sy < VIEW:
                patch = frame[sy * CELL:(sy + 1) * CELL, sx * CELL:(sx + 1) * CELL]
                patch[:] = q["hue"]
                patch[1:3, 1:3] = DARKNESS if (g.beat + i) % 4 < 2 else q["hue"]

        for st in wd.stations:
            sx, sy = st["pos"][0] - g.cam_x, st["pos"][1] - g.cam_y
            if st["pos"] in g.lit and 0 <= sx < VIEW and 0 <= sy < VIEW:
                patch = frame[sy * CELL:(sy + 1) * CELL, sx * CELL:(sx + 1) * CELL]
                hue = GEAR_HUE[st["kind"]]
                if st["kind"] == BOOTS:
                    patch[2:4, :] = hue
                else:
                    patch[0, 1:3] = hue
                    patch[1:4, 1:3] = hue

        sx, sy = g.x - g.cam_x, g.y - g.cam_y
        if 0 <= sx < VIEW and 0 <= sy < VIEW:
            patch = frame[sy * CELL:(sy + 1) * CELL, sx * CELL:(sx + 1) * CELL]
            patch[:] = BODY
            patch[1:3, 1:3] = DARKNESS
            if g.carried is not None:
                patch[1:3, 1:3] = GEAR_HUE[g.carried]

        self._band(frame, g, wd)
        return frame

    def _band(self, frame, g, wd) -> None:
        n = wd.regions
        span = n * CELL
        off = (SCREEN - span) // 2
        for k in range(n):
            on = k in g.done
            if wd.edge in ("top", "bottom"):
                x0 = off + k * CELL
                y0 = 0 if wd.edge == "top" else SCREEN - CELL
            else:
                y0 = off + k * CELL
                x0 = 0 if wd.edge == "left" else SCREEN - CELL
            patch = frame[y0:y0 + CELL, x0:x0 + CELL]
            patch[:] = DARKNESS
            patch[1:3, 1:3] = BAND_ON if on else BAND_OFF


class Cartographer(ARCBaseGame):

    FLASH_FRAMES = 5

    def __init__(self) -> None:
        self.world = WORLDS[0]
        self.cam_x = self.cam_y = 0
        self.x, self.y = self.world.start
        self.carried: int | None = None
        self.entered_with: int | None = None
        self.lit: set = set()
        self.done: set = set()
        self.flash = 0
        self.beat = 0
        camera = Camera(width=SCREEN, height=SCREEN, background=DARKNESS,
                        letter_box=DARKNESS, interfaces=[Window(self)])
        super().__init__(game_id="g309", levels=build_levels(), camera=camera,
                         available_actions=[1, 2, 3, 4])
        self._enter(0)

    def _enter(self, index: int) -> None:
        wd = self.world = WORLDS[index]
        self.x, self.y = wd.start
        self.lit = set()
        self.done = set()
        self.flash = 0
        self._shine()
        self._settle()
        self._follow()
        self._sync()

    def on_set_level(self, level: Level) -> None:
        self.entered_with = self.carried
        self._enter(self.level_index)

    def level_reset(self) -> None:
        super().level_reset()
        self.carried = self.entered_with
        self._enter(self.level_index)

    def full_reset(self) -> None:
        super().full_reset()
        self.carried = None
        self.entered_with = None
        self._enter(self.level_index)

    def _sync(self) -> None:
        found = self.current_level.get_sprites_by_name("body")
        if found:
            found[0].set_position(self.x * CELL, self.y * CELL)

    def _follow(self) -> None:
        wd = self.world
        self.cam_x = max(0, min(max(0, wd.w - VIEW), self.x - VIEW // 2))
        self.cam_y = max(0, min(max(0, wd.h - VIEW), self.y - VIEW // 2))
        self.camera.x = self.cam_x * CELL
        self.camera.y = self.cam_y * CELL

    @property
    def reach(self) -> int:
        return RADIUS[0] if self.carried == LANTERN else RADIUS[1]

    @staticmethod
    def _burden(carried) -> int:
        return 0 if carried is None else WEIGHT[carried]

    def _shine(self) -> None:
        r = self.reach
        wd = self.world
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                cx, cy = self.x + dx, self.y + dy
                if 0 <= cx < wd.w and 0 <= cy < wd.h:
                    self.lit.add((cx, cy))

    def _settle(self) -> None:
        wd = self.world
        for k in range(wd.regions):
            if k not in self.done and wd.owed[k] <= self.lit:
                self.done.add(k)

    def cleared(self) -> bool:
        return len(self.done) >= self.world.regions

    def passable(self, x: int, y: int) -> bool:
        return self.world.walkable(x, y, self.carried == BOOTS)

    def step(self) -> None:
        if self.flash:
            self.flash -= 1
            if self.flash == 0:
                self.next_level()
                self.complete_action()
            return

        self.beat += 1
        delta = {GameAction.ACTION1: (0, -1), GameAction.ACTION2: (0, 1),
                 GameAction.ACTION3: (-1, 0), GameAction.ACTION4: (1, 0)}.get(
                     self.action.id)
        if delta is None:
            self.complete_action()
            return

        nx, ny = self.x + delta[0], self.y + delta[1]
        if self.passable(nx, ny):
            self.x, self.y = nx, ny
            for st in self.world.stations:
                if st["pos"] == (nx, ny):
                    if self._burden(self.carried) + WEIGHT[st["kind"]] > CARRY:
                        self.carried = st["kind"]
                    elif self.carried is None:
                        self.carried = st["kind"]
            self._shine()
            self._settle()

        if self.cleared():
            self.flash = self.FLASH_FRAMES
            self._follow()
            self._sync()
            return

        self._follow()
        self._sync()
        self.complete_action()
