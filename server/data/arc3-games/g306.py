def _hash(x: int, y: int, salt: int) -> int:
    n = (x * 73856093) ^ (y * 19349663) ^ (salt * 83492791)
    n = (n ^ (n >> 13)) & 0xFFFFFFFF
    n = (n * 1274126177) & 0xFFFFFFFF
    return (n ^ (n >> 16)) & 0xFFFFFFFF


def season_of(clock: int, length: int) -> int:
    return (clock // length) % SEASONS


def burden(carried: frozenset) -> int:
    return sum(WEIGHT[k] for k in carried)


def overloaded(carried: frozenset) -> bool:
    return burden(carried) > CARRY


def step_cost(carried: frozenset) -> int:
    return 2 if overloaded(carried) else 1


def walkable(ch: str, season: int, carried: frozenset) -> bool:
    if ch == STONE_CH:
        return False
    if ch == MERE_CH:
        return season == FROST or RAFT in carried
    if ch == DRIFT_CH:
        return season == THAW or CLEATS in carried
    if ch == PASS_CH:
        return season == THAW
    return True


def in_hand(carried: frozenset):
    if RAFT in carried:
        return RAFT
    if CLEATS in carried:
        return CLEATS
    return None


def solid(ch: str) -> bool:
    return ch in (GROUND_CH, ROUGH_CH)


def ashore(world, x: int, y: int, entered_going: int) -> tuple:
    back = -1 if entered_going >= 0 else 1
    d = 1
    while True:
        ch = world.at(x, y + back * d)
        if solid(ch):
            return (x, y + back * d)
        if ch == STONE_CH:
            return (x, y)
        d += 1


