class World:

    def __init__(self, spec: dict) -> None:
        self.w, self.h = spec["w"], spec["h"]
        self.rows = spec["rows"]
        self.start = tuple(spec["start"])
        self.cairn = tuple(spec["cairn"])
        self.season_len = spec["season_len"]
        self.stations = {tuple(pos): kind for pos, kind in spec["stations"]}
        self.props = [dict(pos=tuple(p), hue=PROP_HUE[i % len(PROP_HUE)])
                      for i, p in enumerate(spec["props"])]

    def at(self, x: int, y: int) -> str:
        if not (0 <= x < self.w and 0 <= y < self.h):
            return STONE_CH
        return self.rows[y][x]


WORLDS = [World(s) for s in LEVELS]


def build_levels() -> list[Level]:
    return [Level(sprites=[Sprite(pixels=[[VOID] * CELL] * CELL, name="body",
                                  blocking=BlockingMode.NOT_BLOCKED,
                                  interaction=InteractionMode.INTANGIBLE, layer=1)
                           .set_position(wd.start[0] * CELL, wd.start[1] * CELL)])
            for wd in WORLDS]


class Window(RenderableUserDisplay):

    def __init__(self, game: "Seasons") -> None:
        super().__init__()
        self._g = game

    def render_interface(self, frame: np.ndarray) -> np.ndarray:
        g = self._g
        wd = g.world
        season = g.season
        frame[:] = VOID
        for sy in range(VIEW):
            for sx in range(VIEW):
                wx, wy = sx + g.cam_x, sy + g.cam_y
                if not (0 <= wx < wd.w and 0 <= wy < wd.h):
                    continue
                patch = frame[sy * CELL:(sy + 1) * CELL, sx * CELL:(sx + 1) * CELL]
                ch = wd.at(wx, wy)
                if ch == STONE_CH:
                    patch[:] = STONE_HUE
                    if _hash(wx, wy, 11) % 9 == 0:
                        patch[1:3, 1:3] = VOID
                    continue
                patch[:] = FLOOR_HUE[(ch, season)]
                if ch in (MERE_CH, DRIFT_CH, PASS_CH) and _hash(wx, wy, 23) % 5 == 0:
                    patch[1:3, 1:3] = FLOOR_HUE[(ch, 1 - season)]
                n = _hash(wx, wy, 37)
                if n % 6 == 0:
                    k = (g.clock + n // 6) % 4
                    patch[k // 2 + 1, k % 2 + 1] = FLOOR_HUE[(ch, 1 - season)]

                for kind, cell in g.lying.items():
                    if cell != (wx, wy):
                        continue
                    if cell in wd.stations:
                        patch[:] = GEAR_HUE[kind]
                        patch[1:3, 1:3] = VOID
                    else:
                        patch[:] = CAMP_HUE
                        patch[1:3, 1:3] = GEAR_HUE[kind]

                if (wx, wy) == wd.cairn:
                    patch[:] = CAIRN_HUE
                    patch[1:3, 1:3] = VOID

        for i, q in enumerate(wd.props):
            sx, sy = q["pos"][0] - g.cam_x, q["pos"][1] - g.cam_y
            if 0 <= sx < VIEW and 0 <= sy < VIEW:
                patch = frame[sy * CELL:(sy + 1) * CELL, sx * CELL:(sx + 1) * CELL]
                patch[:] = q["hue"]
                patch[1:3, 1:3] = VOID if (g.clock + i) % 4 < 2 else q["hue"]

        sx, sy = g.x - g.cam_x, g.y - g.cam_y
        if 0 <= sx < VIEW and 0 <= sy < VIEW:
            patch = frame[sy * CELL:(sy + 1) * CELL, sx * CELL:(sx + 1) * CELL]
            patch[:] = BODY
            if len(g.carried) == 1:
                patch[1:3, 1:3] = GEAR_HUE[next(iter(g.carried))]
            elif len(g.carried) == 2:
                patch[1:3, 1:3] = GEAR_HUE[RAFT]
                patch[0, 0] = patch[0, CELL - 1] = GEAR_HUE[CLEATS]
                patch[CELL - 1, 0] = patch[CELL - 1, CELL - 1] = GEAR_HUE[CLEATS]
            else:
                patch[1:3, 1:3] = VOID

        if g.stranded:
            frame[0, :] = CAIRN_HUE
            frame[SCREEN - 1, :] = CAIRN_HUE
            frame[:, 0] = CAIRN_HUE
            frame[:, SCREEN - 1] = CAIRN_HUE
        return frame


class Seasons(ARCBaseGame):

    FLASH_FRAMES = 5

    def __init__(self) -> None:
        self.world = WORLDS[0]
        self.cam_x = self.cam_y = 0
        self.x, self.y = self.world.start
        self.carried: frozenset = frozenset()
        self.entered_with: frozenset = frozenset()
        self.lying: dict = {}
        self.going = 1
        self.clock = 0
        self.stranded = 0
        self.flash = 0
        camera = Camera(width=SCREEN, height=SCREEN, background=VOID, letter_box=VOID,
                        interfaces=[Window(self)])
        super().__init__(game_id="g306", levels=build_levels(),
                         available_actions=[1, 2, 3, 4, 5], camera=camera)
        self._enter(0)

    def _enter(self, index: int) -> None:
        wd = self.world = WORLDS[index]
        self.x, self.y = wd.start
        self.going = 1
        self.clock = 0
        self.stranded = 0
        self.flash = 0
        self.lying = {kind: pos for pos, kind in wd.stations.items()
                      if kind not in self.carried}
        self._follow()
        self._sync()

    def on_set_level(self, level: Level) -> None:
        self.entered_with = self.carried
        self._enter(self.level_index)

    def level_reset(self) -> None:
        super().level_reset()
        self.carried = self.entered_with
        self._enter(self.level_index)

    def full_reset(self) -> None:
        super().full_reset()
        self.carried = frozenset()
        self.entered_with = frozenset()
        self._enter(self.level_index)

    def _sync(self) -> None:
        found = self.current_level.get_sprites_by_name("body")
        if found:
            found[0].set_position(self.x * CELL, self.y * CELL)

    def _follow(self) -> None:
        wd = self.world
        self.cam_x = max(0, min(max(0, wd.w - VIEW), self.x - VIEW // 2))
        self.cam_y = max(0, min(max(0, wd.h - VIEW), self.y - VIEW // 2))
        self.camera.x = self.cam_x * CELL
        self.camera.y = self.cam_y * CELL

    @property
    def season(self) -> int:
        return season_of(self.clock, self.world.season_len)

    def passable(self, x: int, y: int) -> bool:
        return walkable(self.world.at(x, y), self.season, self.carried)

    def step(self) -> None:
        if self.flash:
            self.flash -= 1
            if self.flash == 0:
                self.next_level()
                self.complete_action()
            return

        self.stranded = 0
        wd = self.world
        if self.action.id == GameAction.RESET:
            self.complete_action()
            return
        delta = {GameAction.ACTION1: (0, -1), GameAction.ACTION2: (0, 1),
                 GameAction.ACTION3: (-1, 0), GameAction.ACTION4: (1, 0)}.get(
                     self.action.id)

        if delta is not None:
            nx, ny = self.x + delta[0], self.y + delta[1]
            if self.passable(nx, ny):
                if solid(wd.at(self.x, self.y)) and not solid(wd.at(nx, ny)):
                    self.going = delta[1] if delta[1] else self.going
                self.x, self.y = nx, ny
                for kind in [k for k, cell in self.lying.items() if cell == (nx, ny)]:
                    del self.lying[kind]
                    self.carried = self.carried | {kind}
                if (nx, ny) == wd.cairn:
                    self.flash = self.FLASH_FRAMES
                    self._follow()
                    self._sync()
                    return

        if self.action.id == GameAction.ACTION5:
            kind = in_hand(self.carried)
            here = (self.x, self.y)
            if (kind is not None and solid(wd.at(*here))
                    and here not in self.lying.values() and here != wd.cairn):
                self.carried = self.carried - {kind}
                self.lying[kind] = here

        self.clock += step_cost(self.carried)

        if not self.passable(self.x, self.y):
            self.x, self.y = ashore(wd, self.x, self.y, self.going)
            self.stranded = 1

        self._follow()
        self._sync()
        self.complete_action()
