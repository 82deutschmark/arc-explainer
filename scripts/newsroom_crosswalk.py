# PURPOSE: Build one flat lookup that answers "who is this Kaggle handle, what is their X handle,
# and which team were they on in ARC-2 and in ARC-3?" from the existing newsroom ledgers. It reads
# content/news/people.json (verified accounts), content/news/competitors.json (per-contest teams and
# their member Kaggle handles) and content/news/handle-candidates.json (probable but unconfirmed
# identities) and writes content/news/handle-crosswalk.json plus docs/newsroom/HANDLE_CROSSWALK.md.
# It never writes to people.json or competitors.json and invents nothing: a handle with no verified
# person is listed as "unmapped", a candidate keeps its evidence and confidence.
# Usage: python3.13 scripts/newsroom_crosswalk.py
# SRP/DRY check: Pass - only reads the existing ledgers; does not duplicate newsroom_people.py's
# validation, which still owns what counts as a verified identity.
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PEOPLE = ROOT / 'content/news/people.json'
TEAMS = ROOT / 'content/news/competitors.json'
CANDIDATES = ROOT / 'content/news/handle-candidates.json'
OUT_JSON = ROOT / 'content/news/handle-crosswalk.json'
OUT_MD = ROOT / 'docs/newsroom/HANDLE_CROSSWALK.md'
CONTESTS = ('arc-2', 'arc-3')


def accounts(person, platform):
    return [a['handle'] for a in person.get('accounts', []) if a['platform'] == platform]


def team_row(team):
    return {'teamId': team['teamId'], 'name': team['name'], 'members': team['members'],
            'lastObservedAt': team['lastObservedAt']}


def build():
    people = json.loads(PEOPLE.read_text())
    teams = json.loads(TEAMS.read_text())
    candidates = json.loads(CANDIDATES.read_text()) if CANDIDATES.exists() else []

    # Kaggle handle -> teams per contest. A person can sit on a different team (or none) in each
    # contest, and one Kaggle handle is one person: the team is the unit that changes, not the handle.
    by_handle = {}
    for t in teams:
        for m in t['members']:
            by_handle.setdefault(m.lower(), {c: [] for c in CONTESTS})[t['competition']].append(team_row(t))

    rows, seen = [], set()
    for p in people:
        for k in accounts(p, 'kaggle') or [None]:
            if k is None:
                continue
            seen.add(k.lower())
            rows.append({'name': p['name'], 'personId': p['id'], 'kaggle': k, 'x': accounts(p, 'x'),
                         'status': 'verified', 'teams': by_handle.get(k.lower(), {c: [] for c in CONTESTS})})
    for c in candidates:
        seen.add(c['kaggle'].lower())
        rows.append({'name': c['name'], 'personId': None, 'kaggle': c['kaggle'], 'x': c['x'],
                     'status': 'candidate', 'confidence': c['confidence'], 'evidence': c['evidence'],
                     'teams': by_handle.get(c['kaggle'].lower(), {cc: [] for cc in CONTESTS})})
    unmapped = sorted(h for h in by_handle if h not in seen)
    return {'rows': sorted(rows, key=lambda r: r['kaggle'].lower()), 'unmapped': unmapped}


def cell(teams):
    # Team names such as "V | A | M" contain pipes, which would split a Markdown table cell.
    return '; '.join(f"{t['name']} (#{t['teamId']})".replace('|', '\\|') for t in teams) or '-'


def markdown(data):
    out = ['# Handle crosswalk: Kaggle handle, X handle, team per contest', '',
           'Generated by `scripts/newsroom_crosswalk.py` from `people.json`, `competitors.json` and',
           '`handle-candidates.json`. Do not edit by hand; fix the source ledger and re-run.', '',
           'A **Kaggle handle** is one person. A **team** is a per-contest label with its own id, name and',
           'roster: the same person can be on a different team (or solo) in ARC-2 and in ARC-3. See',
           '[KAGGLE_PRIMER.md](KAGGLE_PRIMER.md).', '',
           '| Person | Kaggle | X | Status | ARC-2 team | ARC-3 team |', '|---|---|---|---|---|---|']
    for r in data['rows']:
        status = r['status'] if r['status'] == 'verified' else f"candidate ({r['confidence']})"
        x = ', '.join('@' + h for h in r['x']) or '-'
        out.append(f"| {r['name']} | {r['kaggle']} | {x} | {status} | {cell(r['teams']['arc-2'])} | {cell(r['teams']['arc-3'])} |")
    out += ['', f"## Kaggle handles on a team with no verified person ({len(data['unmapped'])})", '',
            'Keep the handle; do not guess a name, face or X account. Research them before featuring.', '',
            ', '.join(data['unmapped']), '']
    return '\n'.join(out)


if __name__ == '__main__':
    d = build()
    OUT_JSON.write_text(json.dumps(d, indent=1, ensure_ascii=False) + '\n')
    OUT_MD.write_text(markdown(d))
    print(f"{len(d['rows'])} identities, {len(d['unmapped'])} unmapped team handles")
