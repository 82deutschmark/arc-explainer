#!/usr/bin/env python3.13
# Author: Claude Sonnet 5.5 (effort unknown)
# Date: 30-October-2026
# PURPOSE: Write docs/newsroom/CARD_ART_NEEDS.md, the working list for whoever generates Card Cabinet
# artwork: for every card, what art it has now, whether last year's Hall of Fame card exists, and
# which real photo (Kaggle avatar, ARC Prize page, author page) the artist should build the new
# cyberpunk rendering from. Reads content/news/{cards,people}.json and the Kaggle career evidence;
# makes no network requests. Regenerate after any card, portrait or art change:
#   python3.13 scripts/card_art_needs.py
# SRP/DRY check: Pass — one job (registry -> checklist); the brief itself (CARD_ART_BRIEF.md) is
# hand-written and never duplicated here.
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARDS = json.loads((ROOT / "content/news/cards.json").read_text(encoding="utf-8"))["cards"]
PEOPLE = {p["id"]: p for p in json.loads((ROOT / "content/news/people.json").read_text(encoding="utf-8"))}
EVIDENCE = ROOT / "content/news/evidence/kaggle-careers"
OUT = ROOT / "docs/newsroom/CARD_ART_NEEDS.md"

# Art that is an actual rendering of a person or team (commissioned), as opposed to a photo or avatar.
RENDERED_PREFIXES = ("/news-images/references/", "/news-images/2026-")
# People whose own Kaggle picture is already an ARC Raiders style cyberpunk rendering (small and square).
RENDERED_PORTRAITS = {"mark-barney", "son-pham"}
TIER_WORDS = r"(Novice|Contributor|Expert|Master|Grandmaster)"


def tier(person_id: str) -> str:
    """Highest Competitions tier Kaggle shows on the person's profile, in Kaggle's own words."""
    path = EVIDENCE / f"{person_id}.json"
    if path.is_file():
        value = (json.loads(path.read_text(encoding="utf-8")).get("profile") or {}).get("competitionTier")
        if value:
            return value.replace("Competitions ", "")
    # Mark and Son were checked earlier; their tier sits in a sourced fact ("Kaggle Competitions Expert ...").
    for fact in PEOPLE[person_id].get("facts", []):
        found = re.search(rf"Kaggle Competitions {TIER_WORDS}\b", fact["text"])
        if found:
            return found.group(1)
    return "not recorded"


def kaggle_url(person: dict) -> str:
    account = next((a for a in person.get("accounts", []) if a["platform"] == "kaggle"), None)
    return account["url"] if account else ""


def reference(person: dict) -> str:
    portrait = person.get("portrait")
    if not portrait:
        return "none on file"
    return f"`client/public{portrait['src']}` ({portrait['kind']} picture; source {portrait['sourceUrl']})"


def main() -> None:
    needs_photo, needs_hunt, has_2025, has_2026, teams = [], [], [], [], []
    for card in CARDS:
        number, name = card["number"], card["name"]
        if card["kind"] == "team":
            members = sorted({e["teamId"] for e in card["entries"]})
            line = f"| {number} | {name} | {'2026 art exists: `' + card['art']['src'] + '`' if card.get('art') else '**no art yet**'} | teams {', '.join(members)} |"
            teams.append((bool(card.get("art")), line))
            continue
        person = PEOPLE[card["personId"]]
        art = (card.get("art") or {}).get("src")
        old = next((h["image"]["src"] for h in person.get("hallOfFame", []) if h.get("image") and h["image"].get("src")), None)
        row = f"| {number} | {name} | {tier(person['id'])} | "
        if art and art.startswith(RENDERED_PREFIXES):
            has_2026.append(row + f"`{art}` | {kaggle_url(person)} |")
        elif person.get("editorialPortrait"):
            has_2026.append(row + f"`client/public{person['editorialPortrait']['src']}` | {kaggle_url(person)} |")
        elif person["id"] in RENDERED_PORTRAITS:
            has_2026.append(row + f"`client/public{person['portrait']['src']}` (already a rendering, but small and square) | {kaggle_url(person)} |")
        elif old:
            has_2025.append(row + f"2025 card `client/public{old}` (text baked in) | {kaggle_url(person)} |")
        elif person.get("portrait") and person["portrait"]["kind"] != "hall-of-fame":
            needs_photo.append(row + f"{reference(person)} | {kaggle_url(person)} |")
        else:
            needs_hunt.append(row + f"no photo yet | {kaggle_url(person)} |")

    head = "| No. | Competitor | Kaggle tier | {} | Kaggle profile |\n|---|---|---|---|---|"
    lines = [
        "# Card art: what each card needs",
        "",
        "Generated by `scripts/card_art_needs.py` (Claude Sonnet 5.5, 30 October 2026). Read [CARD_ART_BRIEF.md](CARD_ART_BRIEF.md) first: it says how the art must be composed.",
        "Regenerate after any change: `python3.13 scripts/card_art_needs.py`.",
        "",
        f"## 1. No rendering yet, real photo on file ({len(needs_photo)})",
        "Build the rendering from the photo named in the table.",
        "", head.format("Photo to build from"), *needs_photo, "",
        f"## 2. No rendering yet, no photo on file ({len(needs_hunt)})",
        "Kaggle shows only its default avatar. Find a photo (X, GitHub, LinkedIn, a talk, a team page) and record where it came from before generating.",
        "", head.format("Photo to build from"), *needs_hunt, "",
        f"## 3. Last year's Hall of Fame card exists, 2026 version needed ({len(has_2025)})",
        "Keep last year's card exactly as it is. Make a clean 2026 rendering with no baked-in text, as the brief describes.",
        "", head.format("Last year's card"), *has_2025, "",
        f"## 4. 2026 rendering exists, check it against the brief ({len(has_2026)})",
        "These were made before the composition rules; redo only if the figure collides with the reserved zones.",
        "", head.format("Current art"), *has_2026, "",
        f"## 5. Teams ({len(teams)})",
        "A team card needs a portrait-format group glamour shot of the roster (see the brief).",
        "", "| No. | Team | Art | Kaggle team ids |\n|---|---|---|---|", *[line for _, line in sorted(teams)], "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: photo={len(needs_photo)} hunt={len(needs_hunt)} 2025={len(has_2025)} 2026={len(has_2026)} teams={len(teams)}")


if __name__ == "__main__":
    main()
